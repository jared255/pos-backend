    total numeric(10,2) GENERATED ALWAYS AS (subtotal - discount_total + tax_total) STORED,
    paid_total numeric(10,2) NOT NULL DEFAULT 0,
    balance_due numeric(10,2) GENERATED ALWAYS AS (GREATEST((subtotal - discount_total + tax_total) - paid_total, 0::numeric)) STORED,
    payment_status varchar(15) NOT NULL DEFAULT 'PENDIENTE',
    created_by_user_id bigint NOT NULL,
    placed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sales_order_store
