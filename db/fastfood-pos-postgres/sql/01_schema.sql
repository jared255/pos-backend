CREATE TABLE product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id bigint NOT NULL,
    category_id bigint NOT NULL,
    sku varchar(30),
    name varchar(120) NOT NULL,
    description varchar(255),
