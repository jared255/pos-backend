CREATE OR REPLACE FUNCTION pos.touch_updated_at()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION pos.assign_daily_order_number()
RETURNS trigger AS $$
BEGIN
    IF NEW.business_date IS NULL THEN
        NEW.business_date = CURRENT_DATE;
    END IF;

    IF NEW.order_number IS NULL OR NEW.order_number = 0 THEN
        INSERT INTO pos.daily_order_counter (store_id, business_date, last_value)
        VALUES (NEW.store_id, NEW.business_date, 1)
        ON CONFLICT (store_id, business_date)
        DO UPDATE SET last_value = pos.daily_order_counter.last_value + 1
        RETURNING last_value INTO NEW.order_number;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION pos.prepare_sales_order_item()
RETURNS trigger AS $$
DECLARE
    v_product_name varchar(120);
    v_product_price numeric(10,2);
    v_product_store_id bigint;
    v_order_store_id bigint;
BEGIN
    SELECT p.name, p.price, p.store_id
    INTO v_product_name, v_product_price, v_product_store_id
    FROM pos.product p
    WHERE p.id = NEW.product_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % does not exist', NEW.product_id;
    END IF;

    SELECT so.store_id
    INTO v_order_store_id
    FROM pos.sales_order so
    WHERE so.id = NEW.sales_order_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Sales order % does not exist', NEW.sales_order_id;
    END IF;

    IF v_product_store_id <> v_order_store_id THEN
        RAISE EXCEPTION 'Product % does not belong to store of sales order %', NEW.product_id, NEW.sales_order_id;
    END IF;

    IF NEW.line_number IS NULL THEN
        SELECT COALESCE(MAX(soi.line_number), 0) + 1
        INTO NEW.line_number
        FROM pos.sales_order_item soi
        WHERE soi.sales_order_id = NEW.sales_order_id;
    END IF;

    IF NEW.product_name IS NULL OR btrim(NEW.product_name) = '' THEN
        NEW.product_name = v_product_name;
    END IF;

    IF NEW.unit_price IS NULL THEN
        NEW.unit_price = v_product_price;
    END IF;

    NEW.subtotal = round(NEW.quantity * NEW.unit_price, 2);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION pos.refresh_sales_order_totals(p_sales_order_id bigint)
RETURNS void AS $$
DECLARE
    v_subtotal numeric(10,2);
    v_paid_total numeric(10,2);
    v_discount_total numeric(10,2);
    v_tax_total numeric(10,2);
    v_total numeric(10,2);
BEGIN
    SELECT COALESCE(SUM(soi.subtotal), 0)
    INTO v_subtotal
    FROM pos.sales_order_item soi
    WHERE soi.sales_order_id = p_sales_order_id;

    SELECT COALESCE(SUM(sop.amount), 0)
    INTO v_paid_total
    FROM pos.sales_order_payment sop
    WHERE sop.sales_order_id = p_sales_order_id
      AND sop.status = 'APLICADO';

    SELECT so.discount_total, so.tax_total
    INTO v_discount_total, v_tax_total
    FROM pos.sales_order so
    WHERE so.id = p_sales_order_id;

    v_total = round(v_subtotal - v_discount_total + v_tax_total, 2);

    UPDATE pos.sales_order so
    SET subtotal = v_subtotal,
        paid_total = v_paid_total,
        payment_status = CASE
            WHEN v_total <= 0 THEN 'PAGADO'
            WHEN v_paid_total <= 0 THEN 'PENDIENTE'
            WHEN v_paid_total < v_total THEN 'PARCIAL'
            ELSE 'PAGADO'
        END,
        updated_at = CURRENT_TIMESTAMP
    WHERE so.id = p_sales_order_id;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION pos.sync_sales_order_totals()
RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM pos.refresh_sales_order_totals(OLD.sales_order_id);
        RETURN OLD;
    END IF;

    PERFORM pos.refresh_sales_order_totals(NEW.sales_order_id);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION pos.validate_sales_order_payment()
RETURNS trigger AS $$
DECLARE
    v_requires_reference boolean;
BEGIN
    SELECT pm.requires_reference
    INTO v_requires_reference
    FROM pos.payment_method pm
    WHERE pm.id = NEW.payment_method_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Payment method % does not exist', NEW.payment_method_id;
    END IF;

    IF v_requires_reference AND (NEW.reference_code IS NULL OR btrim(NEW.reference_code) = '') THEN
        RAISE EXCEPTION 'Payment method % requires reference_code', NEW.payment_method_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

