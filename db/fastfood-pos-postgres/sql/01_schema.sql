        FOREIGN KEY (created_by_user_id) REFERENCES app_user (id),
    CONSTRAINT chk_sales_order_order_number_positive CHECK (order_number IS NULL OR order_number > 0),
    CONSTRAINT chk_sales_order_channel
        CHECK (channel IN ('MOSTRADOR', 'LLEVAR', 'DELIVERY', 'APP')),
    CONSTRAINT chk_sales_order_subtotal_non_negative CHECK (subtotal >= 0),
    CONSTRAINT chk_sales_order_discount_non_negative CHECK (discount_total >= 0),
    CONSTRAINT chk_sales_order_tax_non_negative CHECK (tax_total >= 0),
    CONSTRAINT chk_sales_order_paid_total_non_negative CHECK (paid_total >= 0),
    CONSTRAINT chk_sales_order_total_not_negative CHECK ((subtotal + tax_total) >= discount_total),
    CONSTRAINT chk_sales_order_payment_status CHECK (payment_status IN ('PENDIENTE', 'PARCIAL', 'PAGADO')),
    CONSTRAINT uq_sales_order_business_number UNIQUE (store_id, business_date, order_number)
